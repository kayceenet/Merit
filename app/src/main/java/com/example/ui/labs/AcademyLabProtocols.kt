package com.example.ui.labs

data class LabProtocolSpec(
  val aim: String,
  val variables: String,
  val hypothesisPrompt: String,
  val hypothesisOptions: List<String>,
  val correctHypothesisIndex: Int,
  val hypothesisExplanation: String,
  val procedureSteps: List<String>,
  val misconceptionCheck: String,
  val examBridge: String,
)

object AcademyLabProtocols {

  fun protocolFor(lessonId: String, labTitle: String): LabProtocolSpec =
    byLessonId[lessonId]
      ?: LabProtocolSpec(
        aim = "Investigate how the key variables in $labTitle interact mathematically and physically.",
        variables = "Independent: primary control slider • Dependent: measured live output readout",
        hypothesisPrompt = "Before adjusting any control, predict how doubling the primary input affects the system.",
        hypothesisOptions = listOf(
          "The measured output changes monotonically according to the governing law",
          "The output stays strictly fixed regardless of physical inputs",
          "Units convert automatically without changing numerical value",
        ),
        correctHypothesisIndex = 0,
        hypothesisExplanation = "Every physical or mathematical system responds systematically to its independent variable through a conserved rule.",
        procedureSteps = listOf(
          "Record the baseline metric values displayed in the readout banner.",
          "Vary one control at a time while keeping other parameters fixed.",
          "Compare observed ratios against the governing topic formula.",
        ),
        misconceptionCheck = "Always match SI or consistent units before plugging simulated values into an exam formula.",
        examBridge = "WAEC/NECO practicals and JAMB numericals test whether you can spot linear, inverse, or squared relationships from data tables.",
      )

